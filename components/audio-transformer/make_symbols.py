def main():
    write_presets()
    write_asy("atx", "atx", "n=10 Lp=5 Llk=100u Rp=20 Rs=2k Cs=100p",
              "Audio transformer, one primary, one secondary. Pins P1 P2 S1 S2")
    write_asy("atx_sct", "atx_sct", "n=2 Lp=40 Llk=10m Rp=500 Rs=1k Cs=100p",
              "Audio transformer, centre-tapped secondary. Pins P1 P2 S1 SC S2")
    write_asy("atx_ct", "atx_ct", "n=1 Lp=100 Llk=10m Rp=500 Rs=500 Cs=100p",
              "Audio transformer, centre-tapped primary and secondary. Pins P1 PC P2 S1 SC S2")
    for p in PRESETS:
        write_asy(p["name"], p["kind"], "sat=0", f"{p['desc']}. Pins " +
                  " ".join(q[0] for q in PINS[p["kind"]]))
    (HERE / "demo_audio-transformer.asc").write_text(DEMO)
    print("symbols:", ", ".join(["atx", "atx_sct", "atx_ct"] + [p["name"] for p in PRESETS]))


if __name__ == "__main__":
    main()
